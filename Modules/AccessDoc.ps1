        .summary-card.medium .count { color: #fd7e14; }
        .summary-card.low .count { color: #0078d4; }
        .summary-card.info .count { color: #6c757d; }
        .summary-card.total .count { color: #1a1a2e; }

        /* -- Data Tables --------------------------------------------- */
        .data-table {
            width: 100%;
