# AccessDoc.ps1 - DAMOps Access Document Generator
<#
.SYNOPSIS
    New-AccessDoc - Generate formatted, audit-ready HTML/Word documents from
    access audit data.

.DESCRIPTION
    Converts CSV output from Invoke-AccessAudit into a professional, multi-section
    HTML document that can be opened in Microsoft Word and saved as .docx. Includes
    cover page, executive summary, risk tables, recommendations, and appendix.

.NOTES
    File:    AccessDoc.ps1
    Module:  DAMOps
    Author:  DAMOps Team
    Version: 1.0.0
#>

function New-AccessDoc {
    <#
    .SYNOPSIS
        Generate an audit-ready access review document from audit CSV data.

    .DESCRIPTION
        Reads CSV output from Invoke-AccessAudit and produces a professional HTML
        document with 8 sections: Cover, Executive Summary, HIGH/MEDIUM risk tables,
        Guest summary, Privileged roles, Recommendations, and Appendix.
        The document is formatted for both browser viewing and Word .docx conversion.

    .PARAMETER AuditData
        Path to the CSV file generated by Invoke-AccessAudit.

    .PARAMETER Format
        Output format: HTML (default) or Word (same HTML with Word-optimized CSS).

    .PARAMETER OutputPath
        Directory to save output files. Default: ./Output.

    .PARAMETER Tenant
        Tenant name for the document header. Defaults to $env:DAMOPS_TENANT.

    .PARAMETER ReviewerName
        Reviewer/auditor name for the document footer signature section.

    .PARAMETER DryRun
        Show what would be generated without creating the file.

    .EXAMPLE
        New-AccessDoc -AuditData .\Output\audit_report.csv -ReviewerName "Patel, K."

    .EXAMPLE
        New-AccessDoc -AuditData .\Output\audit_report.csv -Format Word -DryRun
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true, HelpMessage = "Path to audit CSV from Invoke-AccessAudit")]
        [ValidateScript({ Test-Path $_ -PathType Leaf })]
        [string]$AuditData,

        [Parameter(HelpMessage = "Output format: HTML or Word")]
        [ValidateSet('HTML', 'Word')]
        [string]$Format = 'HTML',

        [Parameter(HelpMessage = "Output directory path")]
        [string]$OutputPath = (Join-Path (Join-Path $PSScriptRoot '..') 'Output'),

        [Parameter(HelpMessage = "Tenant name for document header")]
        [string]$Tenant = $env:DAMOPS_TENANT,

        [Parameter(HelpMessage = "Reviewer name for signature section")]
        [string]$ReviewerName = 'Not Specified',

        [switch]$DryRun
    )

    $startTime = [DateTime]::UtcNow
    if ([string]::IsNullOrWhiteSpace($Tenant)) { $Tenant = 'Unknown Tenant' }

    # Resolve output path
    $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    if (-not (Test-Path $OutputPath)) {
        New-Item -ItemType Directory -Path $OutputPath -Force | Out-Null
    }

    Write-Verbose "=========================================================="
    Write-Verbose "DAMOps Access Doc Generation"
    Write-Verbose "Input:    $AuditData"
    Write-Verbose "Format:   $Format"
    Write-Verbose "Tenant:   $Tenant"
    Write-Verbose "Reviewer: $ReviewerName"
    Write-Verbose "=========================================================="

    # -- DryRun ---------------------------------------------------------------
    if ($DryRun) {
        Write-Host "`n  [DRYRUN] Access Doc Generation Plan:" -ForegroundColor Cyan
        Write-Host "  -----------------------------------------" -ForegroundColor DarkGray
        Write-Host "  Input CSV:   $AuditData" -ForegroundColor White
        Write-Host "  Format:      $Format" -ForegroundColor White
        Write-Host "  Tenant:      $Tenant" -ForegroundColor White
        Write-Host "  Reviewer:    $ReviewerName" -ForegroundColor White
        Write-Host "  Output Dir:  $OutputPath" -ForegroundColor White
        Write-Host "  -----------------------------------------" -ForegroundColor DarkGray
        Write-Host "  Sections: Cover, Exec Summary, HIGH, MEDIUM, Guests," -ForegroundColor White
        Write-Host "            Privileged Roles, Recommendations, Appendix" -ForegroundColor White
        Write-Host "  [DRYRUN] No document created.`n" -ForegroundColor Yellow

        Write-DAMLog -Action 'NewAccessDoc' -Result 'DRYRUN' -Message "Format=$Format"
        return [PSCustomObject]@{ Status = 'DRYRUN'; Format = $Format }
    }

    # -- Read and parse CSV data ----------------------------------------------
    try {
        Write-Verbose "Reading audit data from: $AuditData"
        $data = Import-Csv -Path $AuditData -Encoding UTF8
        Write-Verbose "  Loaded $($data.Count) records"
    }
    catch {
        Write-DAMLog -Action 'NewAccessDoc' -Result 'FAILED' -Message "CSV read failed: $($_.Exception.Message)"
        throw "Failed to read audit data: $($_.Exception.Message)"
    }

    # -- Calculate statistics -------------------------------------------------
    $totalCount  = $data.Count
    $highRisk    = @($data | Where-Object { $_.RiskFlag -eq 'HIGH' })
    $mediumRisk  = @($data | Where-Object { $_.RiskFlag -eq 'MEDIUM' })
    $lowRisk     = @($data | Where-Object { $_.RiskFlag -eq 'LOW' })
    $infoItems   = @($data | Where-Object { $_.RiskFlag -eq 'INFO' })
    $guests      = @($data | Where-Object { $_.UserType -eq 'Guest' })
    $privileged  = @($data | Where-Object { $_.IsPrivileged -eq 'True' -or $_.IsPrivileged -eq $true })

    # Guest statistics
    $guestCount     = $guests.Count
    $oldestGuest    = if ($guestCount -gt 0) { ($guests | Sort-Object { [int]$_.DaysSinceSignIn } -Descending | Select-Object -First 1).DisplayName } else { 'N/A' }
    $avgGuestDays   = if ($guestCount -gt 0) { [math]::Round(($guests | Measure-Object -Property DaysSinceSignIn -Average).Average, 0) } else { 0 }

    # Stale percentage
    $staleCount     = ($data | Where-Object { [int]$_.DaysSinceSignIn -ge 90 }).Count
    $stalePercent   = if ($totalCount -gt 0) { [math]::Round(($staleCount / $totalCount) * 100, 1) } else { 0 }

    $reviewDate = [DateTime]::UtcNow.ToString('MMMM dd, yyyy')
    $docFileName = "access_review_$($Tenant -replace '[^a-zA-Z0-9]', '_')_$(Get-Date -Format 'yyyyMMdd').html"
    $docPath = Join-Path $OutputPath $docFileName

    Write-Verbose "Statistics: Total=$totalCount, HIGH=$($highRisk.Count), MEDIUM=$($mediumRisk.Count), LOW=$($lowRisk.Count)"

    # -- Build HTML table helper ----------------------------------------------
    function Build-RiskTable {
        param([array]$Users, [string]$RiskLevel)

        if ($Users.Count -eq 0) {
            return "<p class='no-findings'>No $RiskLevel risk findings in this audit period.</p>"
        }

        $rows = ""
        foreach ($u in $Users) {
            $rows += @"
            <tr>
                <td>$($u.DisplayName)</td>
                <td class="upn">$($u.UPN)</td>
                <td>$($u.UserType)</td>
                <td>$($u.Department)</td>
                <td>$($u.Manager)</td>
                <td>$($u.LastSignIn)</td>
                <td class="days">$($u.DaysSinceSignIn)</td>
                <td>$($u.AssignedGroups)</td>
                <td>$($u.IsPrivileged)</td>
                <td class="roles">$($u.PrivilegedRoles)</td>
            </tr>
"@
        }

        return @"
        <table class="data-table">
            <thead>
                <tr>
                    <th>Name</th><th>UPN</th><th>Type</th><th>Dept</th><th>Manager</th>
                    <th>Last Sign-In</th><th>Days Stale</th><th>Groups</th>
                    <th>Privileged</th><th>Roles</th>
                </tr>
            </thead>
            <tbody>
$rows
            </tbody>
        </table>
"@
    }

    # -- Build recommendations ------------------------------------------------
    $recommendations = @()

    if ($highRisk.Count -gt 0) {
        $recommendations += @"
        <li class="rec-critical"><strong>Immediate Action Required:</strong> $($highRisk.Count) privileged account(s) have been inactive for 30+ days while holding elevated directory roles. These accounts represent the highest risk for credential compromise and should be reviewed within 48 hours. Consider revoking active role assignments and converting to PIM-eligible only.</li>
"@
    }

    if ($guestCount -gt 50) {
        $recommendations += @"
        <li class="rec-important"><strong>Guest Lifecycle Policy:</strong> $guestCount guest accounts detected, exceeding the recommended threshold of 50. Implement an automated guest access review policy with quarterly attestation. Remove guests with no sign-in activity exceeding 60 days.</li>
"@
    }
    elseif ($guestCount -gt 0) {
        $recommendations += @"
        <li class="rec-moderate"><strong>Guest Account Review:</strong> $guestCount guest/external account(s) identified. Review external access quarterly and remove accounts no longer required for business collaboration.</li>
"@
    }

    if ($stalePercent -gt 20) {
        $recommendations += @"
        <li class="rec-important"><strong>Access Recertification Campaign:</strong> $stalePercent% of audited accounts are stale (90+ days inactive). This exceeds the 20% threshold and indicates a need for an organization-wide access recertification campaign. Recommend scheduling within 30 days.</li>
"@
    }

    if ($privileged.Count -gt 5) {
        $recommendations += @"
        <li class="rec-moderate"><strong>Privileged Access Reduction:</strong> $($privileged.Count) accounts hold privileged roles. Best practice recommends no more than 5 active Global Administrators. Review role assignments and migrate standing access to PIM just-in-time activation.</li>
"@
    }

    if ($mediumRisk.Count -gt 0) {
        $recommendations += @"
        <li class="rec-moderate"><strong>Monitor Medium Risk Accounts:</strong> $($mediumRisk.Count) account(s) flagged as medium risk due to inactivity combined with significant group memberships. Schedule review within 2 weeks and consider reducing group assignments for inactive accounts.</li>
"@
    }

    # Default recommendation if nothing else triggers
    if ($recommendations.Count -eq 0) {
        $recommendations += @"
        <li class="rec-info"><strong>No Critical Issues:</strong> This audit found no immediate concerns. Continue quarterly reviews and maintain current access governance policies.</li>
"@
    }

    $recsHtml = $recommendations -join "`n"

    # -- Privileged roles section ---------------------------------------------
    $privRows = ""
    foreach ($p in $privileged) {
        $roleList = $p.PrivilegedRoles -split ';' | ForEach-Object { $_.Trim() }
        foreach ($role in $roleList) {
            $roleType = if ($role -match 'PIM Eligible') { 'PIM Eligible' } else { 'Active' }
            $roleName = $role -replace '\s*\(Active\)|\(PIM Eligible\)', '' | ForEach-Object { $_.Trim() }
            $privRows += @"
            <tr>
                <td>$($p.DisplayName)</td>
                <td class="upn">$($p.UPN)</td>
                <td>$($p.Department)</td>
                <td>$roleName</td>
                <td class="role-type-$($roleType.ToLower() -replace ' ', '-')">$roleType</td>
                <td>$($p.LastSignIn)</td>
                <td class="days">$($p.DaysSinceSignIn)</td>
            </tr>
"@
        }
    }

    $privTable = if ($privRows) {
        @"
        <table class="data-table">
            <thead>
                <tr>
                    <th>Name</th><th>UPN</th><th>Department</th><th>Role</th>
                    <th>Assignment Type</th><th>Last Sign-In</th><th>Days Stale</th>
                </tr>
            </thead>
            <tbody>
$privRows
            </tbody>
        </table>
"@
    }
    else {
        "<p class='no-findings'>No privileged role assignments found.</p>"
    }

    # -- Full appendix table --------------------------------------------------
    $appendixRows = ""
    foreach ($u in ($data | Sort-Object { [int]$_.DaysSinceSignIn } -Descending)) {
        $appendixRows += @"
        <tr>
            <td>$($u.DisplayName)</td><td class="upn">$($u.UPN)</td><td>$($u.UserType)</td>
            <td>$($u.Department)</td><td>$($u.Manager)</td><td>$($u.LastSignIn)</td>
            <td class="days">$($u.DaysSinceSignIn)</td><td>$($u.AssignedGroups)</td>
            <td>$($u.IsPrivileged)</td><td class="roles">$($u.PrivilegedRoles)</td>
            <td>$($u.RiskFlag)</td>
        </tr>
"@
    }

    # -- Word-compatibility CSS (mso properties for clean .docx export) -------
    $wordCSS = if ($Format -eq 'Word') {
        @"
        @page { size: letter; margin: 1in; }
        body { mso-line-height-rule: exactly; }
        table { mso-table-lspace: 0pt; mso-table-rspace: 0pt; }
"@
    }
    else { "" }

    # -- Assemble complete HTML document --------------------------------------
    $html = @"
