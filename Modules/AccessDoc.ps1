        .data-table .days { text-align: center; font-weight: 600; }
        .data-table .roles { font-size: 0.75rem; max-width: 200px; }

        /* -- Role type badges ---------------------------------------- */
        .role-type-active {
            color: #dc3545;
            font-weight: 600;
        }
        .role-type-pim-eligible {
