            background: #f8f9fa;
        }
        .rec-critical { border-left-color: #dc3545; background: #fff5f5; }
        .rec-important { border-left-color: #fd7e14; background: #fff8f0; }
        .rec-moderate { border-left-color: #0078d4; background: #f0f7ff; }
