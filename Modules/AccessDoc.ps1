<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>DAMOps Access Review - $Tenant - $reviewDate</title>
    <style>
        /* -- Reset & Base -------------------------------------------- */
        * { margin: 0; padding: 0; box-sizing: border-box; }
        body {
            font-family: 'Segoe UI', Calibri, Arial, sans-serif;
            color: #1a1a2e;
            background: #ffffff;
            line-height: 1.6;
            font-size: 11pt;
        }
        $wordCSS

        /* -- Print styles -------------------------------------------- */
        @media print {
            .page-break { page-break-before: always; }
            body { font-size: 10pt; }
            .no-print { display: none; }
        }

        /* -- Cover Page ---------------------------------------------- */
        .cover {
            text-align: center;
            padding: 4rem 2rem;
            border-bottom: 4px solid #0078d4;
            margin-bottom: 2rem;
        }
        .cover .logo-text {
            font-size: 2.4rem;
            font-weight: 700;
            color: #0078d4;
            letter-spacing: 0.1em;
            margin-bottom: 0.5rem;
        }
        .cover .title {
            font-size: 1.6rem;
            color: #1a1a2e;
            margin-top: 1.5rem;
        }
        .cover .subtitle {
            font-size: 1.1rem;
            color: #555;
            margin-top: 0.5rem;
        }
        .cover .meta {
            margin-top: 2rem;
            font-size: 0.95rem;
            color: #666;
        }
        .cover .meta strong { color: #333; }
        .cover .classification {
            margin-top: 2rem;
            padding: 0.5rem 1.5rem;
            background: #fff3cd;
            border: 1px solid #ffc107;
            border-radius: 4px;
            display: inline-block;
            font-weight: 600;
            color: #856404;
        }

        /* -- Section Headings ---------------------------------------- */
        .section {
            margin: 2rem 1.5rem;
        }
        .section h2 {
            font-size: 1.3rem;
            color: #0078d4;
            border-bottom: 2px solid #0078d4;
            padding-bottom: 0.4rem;
            margin-bottom: 1rem;
        }
        .section h3 {
            font-size: 1.05rem;
            color: #333;
            margin: 1rem 0 0.5rem 0;
        }

        /* -- Executive Summary --------------------------------------- */
        .exec-summary {
            background: #f8f9fa;
            border: 1px solid #dee2e6;
            border-radius: 8px;
            padding: 1.5rem;
            margin-bottom: 1.5rem;
        }
