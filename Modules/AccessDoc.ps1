            <tbody>
                <tr><td><strong>Tool</strong></td><td>DAMOps v1.0.0</td></tr>
                <tr><td><strong>Tenant</strong></td><td>$Tenant</td></tr>
                <tr><td><strong>Run Date</strong></td><td>$reviewDate</td></tr>
                <tr><td><strong>Reviewer</strong></td><td>$ReviewerName</td></tr>
                <tr><td><strong>Total Records</strong></td><td>$totalCount</td></tr>
                <tr><td><strong>Data Source</strong></td><td>$(if ($AuditData -match 'mock') { 'Mock Data' } else { 'Microsoft Graph API' })</td></tr>
            </tbody>
        </table>
    </div>

    <!-- =============================================================== -->
    <!-- SIGNATURE BLOCK                                               -->
    <!-- =============================================================== -->
    <div class="section signature">
        <h2>Reviewer Acknowledgment</h2>
        <p>I have reviewed the findings in this access review report and acknowledge
        the recommendations contained herein.</p>
        <div class="sig-line"></div>
        <p><strong>$ReviewerName</strong></p>
        <p style="color:#999; font-size:0.85rem;">Date: ________________</p>
    </div>

    <!-- =============================================================== -->
    <!-- FOOTER                                                        -->
    <!-- =============================================================== -->
    <div class="footer">
        Generated by DAMOps v1.0.0 | $reviewDate |
        This document is confidential and intended for authorized personnel only.
    </div>

</body>
</html>
"@

    # -- Write document -------------------------------------------------------
    try {
        Set-Content -Path $docPath -Value $html -Encoding UTF8
        Write-Verbose "Document written to: $docPath"
        Write-DAMLog -Action 'NewAccessDoc' -Result 'SUCCESS' -Message "Path=$docPath, Format=$Format, Records=$totalCount"
    }
    catch {
        Write-DAMLog -Action 'NewAccessDoc' -Result 'FAILED' -Message $_.Exception.Message
        throw "Failed to write document: $($_.Exception.Message)"
    }

    $elapsed = ([DateTime]::UtcNow - $startTime).TotalSeconds

    # -- Display summary ------------------------------------------------------
    Write-Host ""
    Write-Host "  /======================================================\" -ForegroundColor DarkCyan
    Write-Host "  |           Access Document Generated                 |" -ForegroundColor DarkCyan
    Write-Host "  |======================================================|" -ForegroundColor DarkCyan
    Write-Host "  |  Sections:    8 (Cover through Appendix)" -ForegroundColor DarkCyan
    Write-Host "  |  Records:     $totalCount" -ForegroundColor DarkCyan
    Write-Host "  |  HIGH Risk:   $($highRisk.Count)" -ForegroundColor DarkCyan
    Write-Host "  |  Format:      $Format" -ForegroundColor DarkCyan
    Write-Host "  |  Duration:    $([math]::Round($elapsed, 1))s" -ForegroundColor DarkCyan
    Write-Host "  \======================================================/" -ForegroundColor DarkCyan
    Write-Host "  -> $docPath" -ForegroundColor Green
    Write-Host ""

    return [PSCustomObject]@{
        Status          = 'SUCCESS'
        Format          = $Format
        DocumentPath    = $docPath
        Tenant          = $Tenant
        TotalRecords    = $totalCount
        HighRisk        = $highRisk.Count
        MediumRisk      = $mediumRisk.Count
        LowRisk         = $lowRisk.Count
        GuestCount      = $guestCount
        PrivilegedCount = $privileged.Count
        Recommendations = $recommendations.Count
        DurationSeconds = [math]::Round($elapsed, 1)
    }
}
