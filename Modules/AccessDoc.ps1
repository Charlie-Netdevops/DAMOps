        }
        .guest-stat {
            padding: 0.8rem 1.2rem;
            background: #f8f9fa;
            border: 1px solid #dee2e6;
            border-radius: 6px;
        }
        .guest-stat .val { font-size: 1.3rem; font-weight: 700; color: #0078d4; }
        .guest-stat .lbl { font-size: 0.8rem; color: #666; }

        /* -- No findings --------------------------------------------- */
        .no-findings {
            padding: 1rem;
