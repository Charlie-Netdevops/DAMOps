# AIRiskSummary.ps1 - DAMOps AI Risk Analysis Module
<#
.SYNOPSIS
    Get-AIRiskSummary - Send audit data to NVIDIA NIM API for AI-powered risk analysis.

.DESCRIPTION
    Reads structured access audit CSV, serializes it to clean JSON, sends it to the
    NVIDIA NIM API (meta/llama-3.3-70b-instruct), and returns a plain-English
    risk summary suitable for executive reporting. Optionally appends the AI section
    to an existing AccessDoc HTML report.

.NOTES
    File:    AIRiskSummary.ps1
    Module:  DAMOps
    Author:  DAMOps Team
    Version: 1.0.0
#>

function Get-AIRiskSummary {
    <#
    .SYNOPSIS
        Generate an AI-powered risk summary from access audit data.

    .DESCRIPTION
        Sends structured audit data to NVIDIA NIM API and receives a plain-English
        risk summary with executive findings, prioritized recommendations, and
        actionable next steps. Saves output as Markdown and optionally appends
        to an existing HTML report.

    .PARAMETER AuditData
        Path to the audit CSV generated by Invoke-AccessAudit.

    .PARAMETER AppendToDoc
        Optional path to an HTML document from New-AccessDoc. The AI summary
        section will be injected into the document.

    .PARAMETER OutputPath
        Directory to save ai_risk_summary.md. Default: ./Output.

    .PARAMETER MaxTokens
        Maximum tokens for AI response. Default: 1024.

    .PARAMETER DryRun
        Show what would be sent to the API without making the call.

    .EXAMPLE
        Get-AIRiskSummary -AuditData .\Output\audit_report.csv

    .EXAMPLE
        Get-AIRiskSummary -AuditData .\Output\audit_report.csv -AppendToDoc .\Output\access_review.html

    .EXAMPLE
        Get-AIRiskSummary -AuditData .\Output\audit_report.csv -DryRun
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true, HelpMessage = "Path to audit CSV from Invoke-AccessAudit")]
        [ValidateScript({ Test-Path $_ -PathType Leaf })]
        [string]$AuditData,

        [Parameter(HelpMessage = "Path to HTML doc to append AI section")]
        [string]$AppendToDoc,

        [Parameter(HelpMessage = "Output directory path")]
        [string]$OutputPath = (Join-Path (Join-Path $PSScriptRoot '..') 'Output'),

        [Parameter(HelpMessage = "Max tokens for AI response")]
        [ValidateRange(256, 4096)]
        [int]$MaxTokens = 1024,

        [switch]$DryRun
    )

    $startTime = [DateTime]::UtcNow
    $tenant    = if ($env:DAMOPS_TENANT) { $env:DAMOPS_TENANT } else { 'Unknown' }

    # Resolve output path
    $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    if (-not (Test-Path $OutputPath)) {
        New-Item -ItemType Directory -Path $OutputPath -Force | Out-Null
    }

    Write-Verbose "=========================================================="
    Write-Verbose "DAMOps AI Risk Summary"
    Write-Verbose "Input:      $AuditData"
    Write-Verbose "Tenant:     $tenant"
    Write-Verbose "MaxTokens:  $MaxTokens"
    Write-Verbose "AppendToDoc:$AppendToDoc"
    Write-Verbose "=========================================================="

    # -- Read and serialize audit data ----------------------------------------
    try {
        Write-Verbose "Reading audit CSV..."
        $csvData = Import-Csv -Path $AuditData -Encoding UTF8
        Write-Verbose "  Loaded $($csvData.Count) records"
    }
    catch {
        Write-DAMLog -Action 'AIRiskSummary' -Result 'FAILED' -Message "CSV read failed: $($_.Exception.Message)"
        throw "Failed to read audit data: $($_.Exception.Message)"
    }

    # Serialize to clean JSON - only selected columns (never send raw AD objects)
    $cleanData = $csvData | Select-Object DisplayName, Department, LastSignIn, `
        DaysSinceSignIn, IsPrivileged, PrivilegedRoles, RiskFlag

    $auditJson = $cleanData | ConvertTo-Json -Depth 3

    # Build context header
    $auditDate  = [DateTime]::UtcNow.ToString('yyyy-MM-dd')
    $totalCount = $csvData.Count
    $highCount  = ($csvData | Where-Object { $_.RiskFlag -eq 'HIGH' }).Count
    $medCount   = ($csvData | Where-Object { $_.RiskFlag -eq 'MEDIUM' }).Count
    $lowCount   = ($csvData | Where-Object { $_.RiskFlag -eq 'LOW' }).Count
    $privCount  = ($csvData | Where-Object { $_.IsPrivileged -eq 'True' -or $_.IsPrivileged -eq $true }).Count

    $contextHeader = "Tenant: $tenant | Audit Date: $auditDate | Total Accounts: $totalCount | HIGH: $highCount | MEDIUM: $medCount | LOW: $lowCount | Privileged Users: $privCount"

    # -- System prompt - IAM cybersecurity analyst persona --------------------
    $systemPrompt = @"
You are a cybersecurity analyst specializing in Identity and Access Management.
You receive structured access audit data from a Microsoft Entra ID environment.
Your job is to:
1. Identify the most critical risk findings in plain English
2. Explain WHY each finding is risky in terms a non-technical manager understands
3. Prioritize findings by business impact, not just technical severity
4. Recommend specific, actionable next steps with realistic timelines
5. Keep the total summary under 400 words
6. Format: Executive Summary (2 sentences) | Top 3 Findings | Recommended Actions
Never use jargon. Never say 'leverage'. Write like you are briefing a director.
"@

    $userMessage = @"
$contextHeader

Access Audit Data:
$auditJson
"@

    # -- DryRun - show what would be sent -------------------------------------
    if ($DryRun) {
        Write-Host "`n  [DRYRUN] AI Risk Summary Plan:" -ForegroundColor Cyan
        Write-Host "  -----------------------------------------" -ForegroundColor DarkGray
        Write-Host "  API Endpoint:  https://integrate.api.nvidia.com/v1/chat/completions" -ForegroundColor White
        Write-Host "  Model:         meta/llama-3.3-70b-instruct" -ForegroundColor White
        Write-Host "  Max Tokens:    $MaxTokens" -ForegroundColor White
        Write-Host "  Records:       $totalCount" -ForegroundColor White
        Write-Host "  Context:       $contextHeader" -ForegroundColor White
        Write-Host "  -----------------------------------------" -ForegroundColor DarkGray
        Write-Host "  System Prompt: $(($systemPrompt -split "`n")[0])..." -ForegroundColor DarkGray
        Write-Host "  User Data:     $($auditJson.Length) characters of serialized JSON" -ForegroundColor DarkGray
        Write-Host "  [DRYRUN] No API call made.`n" -ForegroundColor Yellow

        Write-DAMLog -Action 'AIRiskSummary' -Result 'DRYRUN' -Message "Records=$totalCount, Tokens=$MaxTokens"
        return [PSCustomObject]@{
            Status   = 'DRYRUN'
            Model    = 'meta/llama-3.3-70b-instruct'
            Records  = $totalCount
        }
    }

    # -- Validate API key -----------------------------------------------------
    if ([string]::IsNullOrWhiteSpace($env:NVIDIA_API_KEY)) {
        Write-Warning "NVIDIA_API_KEY not set. Generating fallback summary..."
        $aiSummary = Get-DAMOpsFallbackSummary -TotalCount $totalCount -HighCount $highCount `
            -MediumCount $medCount -LowCount $lowCount -PrivCount $privCount -Tenant $tenant
        $aiStatus = 'FALLBACK'
        Write-DAMLog -Action 'AIRiskSummary' -Result 'SKIPPED' -Message "No API key - using fallback summary"
    }
    else {
        # -- Call NVIDIA NIM API ------------------------------------------
        $aiStatus = 'SUCCESS'

        try {
            Write-Verbose "Calling NVIDIA NIM API..."

            $requestBody = @{
                model       = 'meta/llama-3.3-70b-instruct'
                messages    = @(
                    @{ role = 'system'; content = $systemPrompt }
                    @{ role = 'user';   content = $userMessage }
                )
                max_tokens  = $MaxTokens
                temperature = 0.3
                top_p       = 0.9
            } | ConvertTo-Json -Depth 5

            $headers = @{
                'Authorization' = "Bearer $($env:NVIDIA_API_KEY)"
                'Content-Type'  = 'application/json'
            }

            $response = Invoke-RestMethod `
                -Uri 'https://integrate.api.nvidia.com/v1/chat/completions' `
                -Method POST `
                -Headers $headers `
                -Body $requestBody `
                -TimeoutSec 60 `
                -ErrorAction Stop

            if ($response.choices -and $response.choices[0].message.content) {
                $raw = $response.choices[0].message.content

                # JSON parsing failsafe — if the AI wraps response in markdown
                # or extra text, extract the JSON object reliably
                try {
                    $jsonMatch = [regex]::Match($raw, '\{[\s\S]*\}')
                    if ($jsonMatch.Success) {
                        $null = $jsonMatch.Value | ConvertFrom-Json -ErrorAction Stop
                        Write-Verbose "  Response contained valid JSON block"
                    }
                }
                catch {
                    Write-Verbose "  Response is plain text (not JSON) - using as-is"
                }

                $aiSummary = $raw
                $tokensUsed = if ($response.usage) { $response.usage.total_tokens } else { 'N/A' }
                Write-Verbose "  AI response received - $tokensUsed tokens used"
                Write-DAMLog -Action 'AIRiskSummary' -Result 'SUCCESS' `
                    -Message "Tokens=$tokensUsed, Records=$totalCount"
            }
            else {
                throw "API returned unexpected response format"
            }
        }
        catch {
            Write-Warning "NVIDIA API call failed: $($_.Exception.Message)"
            Write-Warning "Generating fallback summary..."
            $aiSummary = Get-DAMOpsFallbackSummary -TotalCount $totalCount -HighCount $highCount `
                -MediumCount $medCount -LowCount $lowCount -PrivCount $privCount -Tenant $tenant
            $aiStatus = 'FALLBACK'
            Write-DAMLog -Action 'AIRiskSummary' -Result 'FAILED' `
                -Message "API error: $($_.Exception.Message) - used fallback"
        }
    }

    # -- Save Markdown output -------------------------------------------------
    $mdPath = Join-Path $OutputPath 'ai_risk_summary.md'

    $mdContent = @"
# AI Risk Summary - $tenant

**Generated:** $([DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm:ss')) UTC
**Model:** meta/llama-3.3-70b-instruct
**Status:** $aiStatus
**Accounts Analyzed:** $totalCount

---

$aiSummary

---

*Generated by DAMOps v1.0.0 AI Risk Engine*
*Data source: $AuditData*
"@

    try {
        Set-Content -Path $mdPath -Value $mdContent -Encoding UTF8
        Write-Verbose "Markdown saved to: $mdPath"
    }
    catch {
        Write-Warning "Failed to save Markdown: $($_.Exception.Message)"
    }

    # -- Append to HTML document if requested ---------------------------------
    if ($AppendToDoc -and (Test-Path $AppendToDoc)) {
        Write-Verbose "Appending AI section to: $AppendToDoc"

        try {
            $htmlDoc = Get-Content -Path $AppendToDoc -Raw -Encoding UTF8

            # Convert markdown-style summary to HTML
            $aiHtml = $aiSummary `
                -replace '(?m)^## (.+)$', '<h3>$1</h3>' `
                -replace '(?m)^### (.+)$', '<h4>$1</h4>' `
                -replace '(?m)^\*\*(.+?)\*\*', '<strong>$1</strong>' `
                -replace '(?m)^- (.+)$', '<li>$1</li>' `
                -replace '(?m)^(\d+)\. (.+)$', '<li>$2</li>' `
                -replace "`n`n", "</p><p>" `
                -replace "`n", "<br>"

            # Wrap list items
            $aiHtml = $aiHtml -replace '(<li>.+?</li>(?:<br>)?)+', '<ul>$0</ul>'

            $aiSection = @"

    <!-- =============================================================== -->
    <!-- AI RISK ANALYSIS - Generated by NVIDIA NIM                    -->
    <!-- =============================================================== -->
    <div class="section page-break">
        <h2>AI-Powered Risk Analysis</h2>
        <div class="ai-section">
            <h3>Automated Risk Assessment</h3>
            <p style="font-size:0.8rem; color:#666; margin-bottom:1rem;">
                Model: meta/llama-3.3-70b-instruct | Status: $aiStatus |
                Generated: $([DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm:ss')) UTC
            </p>
            <div class="ai-content">
                <p>$aiHtml</p>
            </div>
        </div>
    </div>
"@

            # Insert before the placeholder or before the appendix section
            if ($htmlDoc -match '<!-- DAMOPS_AI_SECTION_PLACEHOLDER -->') {
                $htmlDoc = $htmlDoc -replace '<!-- DAMOPS_AI_SECTION_PLACEHOLDER -->', $aiSection
            }
            else {
                # Insert before the closing </body> tag
                $htmlDoc = $htmlDoc -replace '</body>', "$aiSection`n</body>"
            }

            Set-Content -Path $AppendToDoc -Value $htmlDoc -Encoding UTF8
            Write-Verbose "  AI section injected into HTML document"
            Write-DAMLog -Action 'AIAppendDoc' -Result 'SUCCESS' -Message "Path=$AppendToDoc"
        }
        catch {
            Write-Warning "Failed to append AI section to document: $($_.Exception.Message)"
            Write-DAMLog -Action 'AIAppendDoc' -Result 'FAILED' -Message $_.Exception.Message
        }
    }

    $elapsed = ([DateTime]::UtcNow - $startTime).TotalSeconds

    # -- Display summary ------------------------------------------------------
    $statusColor = switch ($aiStatus) {
        'SUCCESS'  { 'Green' }
        'FALLBACK' { 'Yellow' }
        default    { 'Red' }
    }

    Write-Host ""
    Write-Host "  /======================================================\" -ForegroundColor DarkCyan
    Write-Host "  |           AI Risk Summary Complete                  |" -ForegroundColor DarkCyan
    Write-Host "  |======================================================|" -ForegroundColor DarkCyan
    Write-Host "  |  AI Status:    " -NoNewline -ForegroundColor DarkCyan
    Write-Host "$aiStatus" -ForegroundColor $statusColor
    Write-Host "  |  Model:        meta/llama-3.3-70b-instruct" -ForegroundColor DarkCyan
    Write-Host "  |  Records:      $totalCount analyzed" -ForegroundColor DarkCyan
    Write-Host "  |  Duration:     $([math]::Round($elapsed, 1))s" -ForegroundColor DarkCyan
    Write-Host "  \======================================================/" -ForegroundColor DarkCyan
    Write-Host "  -> $mdPath" -ForegroundColor Green

    if ($AppendToDoc -and (Test-Path $AppendToDoc)) {
        Write-Host "  -> $AppendToDoc (AI section appended)" -ForegroundColor Green
    }
    Write-Host ""

    return [PSCustomObject]@{
        Status          = $aiStatus
        Model           = 'meta/llama-3.3-70b-instruct'
        RecordsAnalyzed = $totalCount
        SummaryPath     = $mdPath
        AppendedToDoc   = if ($AppendToDoc) { $AppendToDoc } else { $null }
        Summary         = $aiSummary
        DurationSeconds = [math]::Round($elapsed, 1)
    }
}


# -- Fallback summary generator (when API is unavailable) ---------------------
function Get-DAMOpsFallbackSummary {
    <#
    .SYNOPSIS
        Generate a structured risk summary when the NVIDIA API is unavailable.
    #>
    [CmdletBinding()]
    param(
        [int]$TotalCount,
        [int]$HighCount,
        [int]$MediumCount,
        [int]$LowCount,
        [int]$PrivCount,
        [string]$Tenant
    )

    $summary = @"
## Executive Summary

This access review of the $Tenant tenant analyzed $TotalCount accounts and identified $HighCount critical findings requiring immediate attention. A total of $PrivCount privileged accounts were found, with $HighCount showing signs of dormancy that represent significant security exposure.

## Top 3 Findings

### 1. Dormant Privileged Accounts (CRITICAL)
$HighCount account(s) hold elevated directory roles (such as Global Administrator) but have not signed in for 30+ days. These dormant privileged accounts are prime targets for credential compromise because an attacker can use stolen credentials without triggering behavioral anomaly alerts.

### 2. Stale Access with Broad Group Membership (HIGH)
$MediumCount account(s) are inactive for 60-90 days while retaining significant group memberships. These accounts can access shared resources, file shares, and team channels long after the person has stopped actively using them.

### 3. External Guest Account Accumulation (MODERATE)
Guest accounts represent external trust relationships. Without regular attestation, these accounts can provide persistent access paths into the organization for former partners, vendors, and contractors.

## Recommended Actions

1. **Within 48 hours:** Review and revoke active privileged role assignments for all $HighCount HIGH-risk accounts. Convert to PIM eligible-only where the role is still needed.
2. **Within 2 weeks:** Conduct a targeted access review for all $MediumCount MEDIUM-risk accounts. Remove unnecessary group memberships and disable accounts with no business justification.
3. **Within 30 days:** Implement an automated guest access review policy with quarterly attestation cycles. Set a maximum guest lifetime of 180 days with mandatory re-approval.
4. **Ongoing:** Enable PIM for all privileged roles and require justification + approval for each activation. Set maximum activation duration to 8 hours.

---

*⚠️ This is an automated fallback summary. For AI-powered analysis, configure the NVIDIA_API_KEY environment variable.*
"@

    return $summary
}
